USE ROLE ACCOUNTADMIN;

# Creating resource monitor
CREATE OR REPLACE RESOURCE MONITOR rm_perf_lab 
    WITH CREDIT_QUOTA = 20 
    FREQUENCY = MONTHLY
    START_TIMESTAMP = IMMEDIATELY
    TRIGGERS ON 75 PERCENT DO NOTIFY 
    ON 100 PERCENT DO SUSPEND 
    ON 110 PERCENT DO SUSPEND_IMMEDIATE ;

# Three warehouses for the size test, all small cost settings 

CREATE OR REPLACE WAREHOUSE wh_xs WAREHOUSE_SIZE= 'XSMALL'
AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE OR REPLACE WAREHOUSE wh_s WAREHOUsSE_SIZE = 'SMALL'
AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE OR REPLACE WAREHOUSE wh_m WAREHOUSE_SIZE ='MEDIUM'
AUTO_SUSPEND=60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;


SHOW WAREHOUSES;

# Creating Database and schema

CREATE OR REPLACE DATABASE perf_lab;
CREATE OR REPLACE SCHEMA perf_lab.tpch;

# CREATING ROLES 

CREATE ROLE IF NOT EXISTS engineer_role;
CREATE ROLE IF NOT EXISTS analyst_role;

GRANT USAGE ON WAREHOUSE wh_s TO ROLE engineer_role;
GRANT USAGE ON WAREHOUSE wh_xs TO ROLE engineer_role;
GRANT USAGE ON WAREHOUSE wh_m TO ROLE engineer_role;
GRANT USAGE ON WAREHOUSE wh_s TO ROLE analyst_role;
GRANT USAGE ON DATABASE perf_lab TO ROLE engineer_role;
GRANT ALL PRIVILEGES ON SCHEMA perf_lab.tpch TO ROLE engineer_role;
GRANT IMPORTED PRIVILEGES ON DATABASE snowflake TO ROLE engineer_role;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE engineer_role;


GRANT USAGE ON SCHEMA perf_lab.tpch TO ROLE analyst_role;
GRANT SELECT ON FUTURE TABLES IN SCHEMA perf_lab.tpch TO ROLE analyst_role;

GRANT ROLE engineer_role TO USER DHARSANA;
GRANT ROLE analyst_role TO USER DHARSANA;
